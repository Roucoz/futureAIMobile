/**
 * Sets the API target by regenerating src/config/env.target.ts.
 *
 * Usage:
 *   node scripts/set-target.js prod   # "Tuxon"     → https://api.tuxon.ai
 *   node scripts/set-target.js dev    # "Tuxon Dev" → https://dev-api.tuxon.ai
 *   node scripts/set-target.js local  # local dev   → http://localhost:4010
 */
const fs = require('fs');
const path = require('path');

const target = process.argv[2];
const allowed = ['prod', 'dev', 'local'];
if (!allowed.includes(target)) {
  console.error('Usage: node scripts/set-target.js <prod|dev|local>');
  process.exit(1);
}

const file = path.join(__dirname, '..', 'src', 'config', 'env.target.ts');
const content = `/**
 * API target.
 *
 * Generated by \`npm run target:prod|dev|local\`.
 *   - 'prod'  → "Tuxon"     (com.tuxon.app)  → https://api.tuxon.ai
 *   - 'dev'   → "Tuxon Dev" (com.tuxon.dev)  → https://dev-api.tuxon.ai
 *   - 'local' → local backend                → http://localhost:4010 (debug only)
 *
 * Store/release builds must use 'prod' or 'dev'. 'local' is http and is
 * rejected by the HTTPS guard in env.ts for release bundles. This file is
 * safe to commit and defaults to 'prod'.
 */
export type AppTarget = 'prod' | 'dev' | 'local';

export const APP_TARGET: AppTarget = '${target}';
`;

fs.writeFileSync(file, content, 'utf8');
console.log(`APP_TARGET set to '${target}' in src/config/env.target.ts`);
